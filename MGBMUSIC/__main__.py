# HTTP Server for Render health checks with HTML Buttons
class HealthCheckHandler(BaseHTTPRequestHandler):
    """Simple HTTP handler for Render health checks"""
    
    def do_GET(self):
        """Handle GET requests with HTML buttons"""
        self.send_response(200)
        self.send_header('Content-type', 'text/html; charset=utf-8')
        self.end_headers()
        btn_channel = html_button("MGBMUSIC Channel", url="https://t.me/MGB_SUPPROT_GROUP")
        btn_group = html_button("MGB NOT FREE CODER", url="https://t.me/mgb_not_free_coder")
        html_page = f"""<!DOCTYPE html>
<html>
<head><title>MGBMUSIC Bot</title></head>
<body style="font-family:sans-serif;text-align:center;padding:40px;background:#0f172a;color:#fff;">
  <h2>MGBMUSIC Bot is Running</h2>
  <p>Powered by MGB NOT FREE CODER (@MGB_NOT_FREE)</p>
  <div style="margin-top:20px;display:flex;gap:12px;justify-content:center;">
    {btn_channel}
    {btn_group}
  </div>
</body>
</html>"""
        self.wfile.write(html_page.encode('utf-8'))
    
    def log_message(self, format, *args):
        """Suppress log messages to keep console clean"""
        pass


def run_http_server():
    """Run a simple HTTP server for Render health checks"""
    port = int(os.environ.get("PORT", 8000))
    server = HTTPServer(('0.0.0.0', port), HealthCheckHandler)
    logger.info(f"🌐 HTTP health check server started on port {port}")
    server.serve_forever()


async def main():
    try:
        # Step 1: Validate required environment variables
        try:
            config.check()
        except SystemExit as e:
            logger.error(str(e))
            return

        # Step 2: Start HTTP server in a separate thread (for Render)
        http_thread = threading.Thread(target=run_http_server, daemon=True)
        http_thread.start()
        logger.info("🌐 HTTP server thread started for Render health checks")

        # Step 3: Connect to MongoDB database
        await db.connect()
        
        # Step 4: Start the main bot client
        await app.boot()
        
        # Step 5: Start assistant/userbot clients (for joining voice chats)
        await userbot.boot()
        
        # Step 6: Initialize voice call handler
        await tune.boot()

        # Step 7: Load all plugin modules (commands like /play, /pause, etc.)
        for module in all_modules:
            try:
                importlib.import_module(f"MGBMUSIC.plugins.{module}")
            except Exception as e:
                logger.error(f"Failed to load plugin {module}: {e}", exc_info=True)
        # MGBMUSIC group-manager modules (MGBMUSIC/MGBMUSIC/)
        for module in mgbmusic_modules:
            try:
                importlib.import_module(f"MGBMUSIC.MGBMUSIC.{module}")
            except Exception as e:
                logger.error(f"Failed to load MGBMUSIC module {module}: {e}", exc_info=True)
        logger.info(f"🔌 Loaded {len(all_modules) + len(mgbmusic_modules)} plugin modules.")

        # Set Telegram command menu
        try:
            await app.set_bot_commands(BOT_COMMANDS)
            logger.info(f"📋 Set {len(BOT_COMMANDS)} bot commands.")
        except Exception as e:
            logger.error(f"Failed to set bot commands: {e}")

        # Step 8: Load sudo users and blacklisted users from database
        sudoers = await db.get_sudoers()
        app.sudoers.update(sudoers)  # Add sudo users to set
        app.sudo_filter.update(sudoers)  # Add sudo users to filter
        app.bl_users.update(await db.get_blacklisted())  # Add blacklisted users to filter
        logger.info(f"👑 Loaded {len(app.sudoers)} sudo users.")
        logger.info("\n🎉 MGBMUSIC Bot started successfully! Ready to play music! 🎵\n")

        # Step 9: Keep the bot running (press Ctrl+C to stop)
        try:
            await idle()
        except KeyboardInterrupt:
            logger.info("Received stop signal...")
        except Exception as e:
            logger.error(f"Error during idle: {e}", exc_info=True)
        
        # Step 10: Cleanup and shutdown when bot is stopped
        await stop()
    except Exception as e:
        logger.error(f"Critical error in main: {e}", exc_info=True)
        raise


if __name__ == "__main__":
    try:
        loop = asyncio.get_event_loop()
        loop.run_until_complete(main())
    except KeyboardInterrupt:
        logger.info("Bot stopped by user (Ctrl+C)")
    except SystemExit as e:
        logger.error(f"Bot exited with system error: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error caused bot to stop: {e}", exc_info=True)
        # Don't raise - allow clean shutdown
    finally:
        # Ensure cleanup happens
        try:
            loop = asyncio.get_event_loop()
            if loop.is_running():
                loop.stop()
        except:
            pass
